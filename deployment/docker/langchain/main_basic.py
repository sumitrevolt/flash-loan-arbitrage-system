#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Basic LangChain Container - Minimal Dependencies Version
"""

import asyncio
import json
import os
import logging
import time
from datetime import datetime
from typing import Dict, Any, Optional, List

import uvicorn
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler()
    ]
)
logger = logging.getLogger(__name__)

# Response models
class HealthResponse(BaseModel):
    status: str
    cursor_api: bool = False
    langchain: bool = False
    timestamp: str
    container: str = "langchain-coordinator"
    dependencies: Dict[str, bool] = Field(default_factory=dict)

class BasicRequest(BaseModel):
    prompt: str = Field(..., description="The prompt to process")
    agent_type: str = Field(default="basic", description="Type of agent")

class BasicResponse(BaseModel):
    response: str = Field(..., description="Agent response")
    agent_type: str = Field(..., description="Agent type used")
    timestamp: str
    status: str = "success"

