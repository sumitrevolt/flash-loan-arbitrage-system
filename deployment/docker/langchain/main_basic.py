# Initialize FastAPI app
app = FastAPI(
    title="LangChain Flash Loan Coordinator (Basic)",
    description="Minimal version for testing and development",
    version="0.1.0-basic"
)

# Add CORS middleware
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Global state
mock_agent = MockAgent()

@app.on_event("startup")
async def startup_event():
    """Startup event handler"""
    logger.info("🚀 LangChain Coordinator (Basic Mode) starting up...")
    logger.info("📝 This is a minimal version with mock responses")
    logger.info("🔧 Add full dependencies and Cursor API for complete functionality")

@app.get("/health", response_model=HealthResponse)
async def health_check():
    """Health check endpoint"""
    cursor_available = bool(os.getenv('CURSOR_API_KEY'))
    
    dependencies = {
        "fastapi": True,
        "uvicorn": True,
        "pydantic": True,
        "cursor_api": cursor_available,
        "langchain": False,  # Not installed in basic mode
        "transformers": False,  # Not installed in basic mode
        "torch": False,  # Not installed in basic mode
    }
    
    return HealthResponse(
        status="healthy",
        cursor_api=cursor_available,
        langchain=False,
        timestamp=datetime.now().isoformat(),
        dependencies=dependencies
    )

@app.post("/langchain/chat", response_model=BasicResponse)
async def chat_with_langchain(request: BasicRequest):
    """Basic chat endpoint with mock responses"""
    try:
        response = await mock_agent.process(request.prompt)
        
        return BasicResponse(
            response=response,
            agent_type=request.agent_type,
            timestamp=datetime.now().isoformat()
        )
    
    except Exception as e:
        logger.error(f"Error processing request: {e}")
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/langchain/code-generation")
async def generate_code(prompt: str, language: str = "python"):
    """Mock code generation endpoint"""
    try:
        mock_request = BasicRequest(prompt=f"Generate {language} code: {prompt}")
        response = await mock_agent.process(mock_request.prompt)
        
        return {
            "code": response,
            "language": language,
            "timestamp": datetime.now().isoformat(),
            "status": "mock_generated"
        }
    
    except Exception as e:
        logger.error(f"Error generating code: {e}")
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/langchain/contract-audit")
async def audit_contract(contract_code: str, contract_type: str = "arbitrage"):
    """Mock contract audit endpoint"""
    try:
        audit_prompt = f"Audit this {contract_type} contract: {contract_code[:200]}..."
        response = await mock_agent.process(audit_prompt)
        
        return {
            "audit_report": response,
            "contract_type": contract_type,
            "timestamp": datetime.now().isoformat(),
            "status": "mock_audited",
            "issues_found": 0,
            "recommendations": ["Enable Cursor API for real audit analysis"]
        }
    
    except Exception as e:
        logger.error(f"Error auditing contract: {e}")
        raise HTTPException(status_code=500, detail=str(e))

@app.get("/status")
async def get_status():
    """Get detailed status information"""
